"""Repair issues for the Kilowahti integration."""

from __future__ import annotations

import logging
from datetime import datetime, timedelta

import voluptuous as vol

from homeassistant.components.repairs import ConfirmRepairFlow, RepairsFlow
from homeassistant.config_entries import ConfigEntry
from homeassistant.core import HomeAssistant
from homeassistant.helpers import issue_registry as ir
from homeassistant.util import dt as dt_util

from ._migrate import (
    async_find_renamable_entity_ids,
    async_plan_stable_renames,
    async_rename_to_stable_entity_ids,
)
from .const import DOMAIN

_LOGGER = logging.getLogger(__name__)

STALE_FAILOVER_THRESHOLD = timedelta(hours=24)
FAQ_URL = "https://docs.kilowahti.fi/faq/"
ENTITIES_URL = "https://docs.kilowahti.fi/entities/"


def failover_issue_id(entry_id: str) -> str:
    return f"stale_failover_{entry_id}"


def async_update_failover_issue(
    hass: HomeAssistant,
    *,
    entry_id: str,
    region: str,
    active_name: str,
    primary_name: str,
    last_failover_utc: datetime | None,
) -> None:
    """Create or clear the stale-failover repair issue for a config entry.

    Called on every successful price fetch. Creates the issue once the active
    source has differed from the primary for longer than STALE_FAILOVER_THRESHOLD;
    clears it as soon as the primary source is active again.
    """
    issue_id = failover_issue_id(entry_id)

    if active_name == primary_name:
        ir.async_delete_issue(hass, DOMAIN, issue_id)
        return

    if last_failover_utc is None:
        return

    if dt_util.utcnow() - last_failover_utc < STALE_FAILOVER_THRESHOLD:
        return

    ir.async_create_issue(
        hass,
        DOMAIN,
        issue_id,
        is_fixable=False,
        severity=ir.IssueSeverity.WARNING,
        translation_key="stale_failover",
        translation_placeholders={
            "region": region,
            "fallback_source": active_name,
            "primary_source": primary_name,
            "faq_url": FAQ_URL,
        },
        learn_more_url=FAQ_URL,
    )


def stable_entity_ids_issue_id(entry_id: str) -> str:
    return f"stable_entity_ids_{entry_id}"


def async_check_stable_entity_ids(hass: HomeAssistant, entry: ConfigEntry) -> None:
    """Offer to move auto-generated entity IDs to the stable scheme.

    Must run before the platforms load: loading refreshes the display names in the
    registry, and an ID is recognised as auto-generated by matching those names.
    The entity list is stored on the issue, which is left alone once it exists.
    """
    issue_id = stable_entity_ids_issue_id(entry.entry_id)
    if ir.async_get(hass).async_get_issue(DOMAIN, issue_id) is not None:
        return

    entity_ids = async_find_renamable_entity_ids(hass, entry)
    if not entity_ids:
        return

    ir.async_create_issue(
        hass,
        DOMAIN,
        issue_id,
        is_fixable=True,
        is_persistent=True,
        severity=ir.IssueSeverity.WARNING,
        translation_key="stable_entity_ids",
        translation_placeholders={
            "name": entry.title,
            "count": str(len(entity_ids)),
            "entities_url": ENTITIES_URL,
        },
        learn_more_url=ENTITIES_URL,
        data={"entry_id": entry.entry_id, "entity_ids": ",".join(entity_ids)},
    )


# Item types of Home Assistant's search integration that hold entity references.
_USAGE_TYPES = ("automation", "script", "scene", "group")
_USAGE_LIMIT = 10


def async_find_entity_usage(hass: HomeAssistant, entity_ids: list[str]) -> list[str]:
    """Name the automations, scripts, scenes and groups that reference the entities.

    Dashboards and templates are not covered by Home Assistant's search. Returns an
    empty list when the search is unavailable.
    """
    try:
        from homeassistant.components.search import ItemType, Searcher
        from homeassistant.helpers.entity import entity_sources

        found: set[str] = set()
        for entity_id in entity_ids:
            related = Searcher(hass, entity_sources(hass)).async_search(ItemType.ENTITY, entity_id)
            for item_type in _USAGE_TYPES:
                found.update(related.get(item_type, ()))
    except Exception:  # noqa: BLE001 - the list is advisory; never block the rename
        _LOGGER.debug("Entity usage search failed", exc_info=True)
        return []

    names = []
    for item_id in sorted(found):
        state = hass.states.get(item_id)
        names.append(f"{state.name} (`{item_id}`)" if state else f"`{item_id}`")
    return names


class StableEntityIdsFlow(ConfirmRepairFlow):
    """Show where the entities are used, then rename them after the user confirms."""

    def __init__(self, entry_id: str, entity_ids: list[str]) -> None:
        self._entry_id = entry_id
        self._entity_ids = entity_ids

    async def async_step_confirm(self, user_input: dict[str, str] | None = None):
        if user_input is not None:
            async_rename_to_stable_entity_ids(self.hass, self._entry_id, self._entity_ids)
            return self.async_create_entry(data={})

        plan = async_plan_stable_renames(self.hass, self._entry_id, self._entity_ids)
        usage = async_find_entity_usage(self.hass, list(plan))
        shown = [f"- {item}" for item in usage[:_USAGE_LIMIT]]
        if len(usage) > _USAGE_LIMIT:
            shown.append(f"- … (+{len(usage) - _USAGE_LIMIT})")

        issue = ir.async_get(self.hass).async_get_issue(self.handler, self.issue_id)
        return self.async_show_form(
            step_id="confirm" if usage else "confirm_no_references",
            data_schema=vol.Schema({}),
            description_placeholders={
                **(issue.translation_placeholders if issue else {}),
                "count": str(len(plan)),
                "usage": "\n".join(shown),
            },
        )

    async def async_step_confirm_no_references(self, user_input: dict[str, str] | None = None):
        return await self.async_step_confirm(user_input)


async def async_create_fix_flow(
    hass: HomeAssistant, issue_id: str, data: dict[str, str | int | float | None] | None
) -> RepairsFlow:
    """Create the fix flow for a fixable issue."""
    assert data is not None
    return StableEntityIdsFlow(str(data["entry_id"]), str(data["entity_ids"]).split(","))
